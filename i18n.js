const originalTexts = new WeakMap();

function getOriginalOrSet(node, val) {
    let orig = originalTexts.get(node);
    if (!orig) {
        orig = val;
        originalTexts.set(node, orig);
    }
    return orig;
}

function translateStr(orig, lang) {
    const key = orig.trim();
    if (!key) return orig;
    if (lang === 'en') return orig;
    if (dict[key] && dict[key][lang]) {
        return orig.replace(key, dict[key][lang]);
    }
    
    let match = orig.match(/^(\d+)\s+Patients?$/i);
    if(match) return match[1] + (lang === 'hi' ? ' मरीज' : ' रुग्ण');
    
    match = orig.match(/^(\d+)\s+Doctors?$/i);
    if(match) return match[1] + ' डॉक्टर';

    match = orig.match(/^Error:\s+(.+)$/i);
    if(match) return (lang === 'hi' ? 'त्रुटि: ' : 'त्रुटी: ') + translateStr(match[1], lang);

    return orig;
}

function updateDOM(lang) {
    function walk(node) {
        if (node.nodeType === Node.TEXT_NODE) {
            const orig = getOriginalOrSet(node, node.nodeValue);
            const translated = translateStr(orig, lang);
            if (node.nodeValue !== translated) node.nodeValue = translated;
        } else if (node.nodeType === Node.ELEMENT_NODE) {
            if (node.tagName === 'SCRIPT' || node.tagName === 'STYLE' || node.id === 'global-lang-selector') return;

            if (node.placeholder) {
                const orig = getOriginalOrSet(node, node.placeholder);
                node.placeholder = translateStr(orig, lang);
            }
            if (node.tagName === 'INPUT' && (node.type === 'button' || node.type === 'submit')) {
                const orig = getOriginalOrSet(node, node.value);
                node.value = translateStr(orig, lang);
            }
            for (let child of node.childNodes) walk(child);
        }
    }
    walk(document.body);
    document.documentElement.lang = lang;
}

const origAlert = window.alert;
window.alert = function(msg) {
    const lang = localStorage.getItem('appLang') || 'en';
    origAlert(translateStr(msg, lang));
};

let observer;

function changeLang(lang) {
    localStorage.setItem('appLang', lang);
    if(observer) observer.disconnect();
    updateDOM(lang);
    if(observer) observer.observe(document.body, { childList: true, subtree: true });
}

document.addEventListener('DOMContentLoaded', () => {
    const lang = localStorage.getItem('appLang') || 'en';
    const selectors = document.querySelectorAll('.global-lang-selector');
    selectors.forEach(selector => {
        selector.value = lang;
        selector.addEventListener('change', (e) => changeLang(e.target.value));
    });
    updateDOM(lang);

    observer = new MutationObserver(() => {
        observer.disconnect();
        updateDOM(localStorage.getItem('appLang') || 'en');
        observer.observe(document.body, { childList: true, subtree: true });
    });
    observer.observe(document.body, { childList: true, subtree: true });
});


